#!/usr/bin/env bash
#
# Builds the signed release APK and copies it into release/.
#
# On first run a signing key is created together with a random password, which
# is written to keystore/keystore.properties. Keep that file safe and back it
# up: without it the key cannot be used again. Both the keystore and the
# properties file are git-ignored.
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

: "${ANDROID_HOME:=${ANDROID_SDK_ROOT:-}}"
if [[ -z "$ANDROID_HOME" ]]; then
  echo "ANDROID_HOME (or ANDROID_SDK_ROOT) must point at an Android SDK" >&2
  exit 1
fi

KEYSTORE_PATH="${ROULETTE_KEYSTORE:-$ROOT_DIR/keystore/release.jks}"
PROPERTIES_PATH="$(dirname "$KEYSTORE_PATH")/keystore.properties"
KEY_ALIAS="${ROULETTE_KEY_ALIAS:-roulette}"

random_password() {
  # 48 hex characters (192 bits) from /dev/urandom. od reads a fixed number of
  # bytes and exits cleanly, so it does not trip pipefail the way `tr | head` does.
  LC_ALL=C od -An -N24 -tx1 /dev/urandom | tr -d ' \n'
}

# Reads a value from the properties file without sourcing it, so passwords may
# contain spaces or shell metacharacters.
read_property() {
  local key="$1" line
  [[ -f "$PROPERTIES_PATH" ]] || return 1
  while IFS= read -r line || [[ -n "$line" ]]; do
    case "$line" in
      "$key"=*) printf '%s' "${line#"$key"=}"; return 0 ;;
    esac
  done < "$PROPERTIES_PATH"
  return 1
}

if [[ ! -f "$KEYSTORE_PATH" ]]; then
  echo "No keystore at $KEYSTORE_PATH, generating one"
  mkdir -p "$(dirname "$KEYSTORE_PATH")"
  # Use the caller's passwords when given, so the same environment can sign
  # again later; only invent values that were not provided.
  STORE_PASSWORD="${ROULETTE_STORE_PASSWORD:-$(random_password)}"
  KEY_PASSWORD="${ROULETTE_KEY_PASSWORD:-$STORE_PASSWORD}"
  # JKS honours a key password that differs from the store password; PKCS12
  # (the JDK default) silently ignores -keypass in that case.
  keytool -genkeypair -v \
    -keystore "$KEYSTORE_PATH" \
    -storetype JKS \
    -storepass "$STORE_PASSWORD" \
    -keypass "$KEY_PASSWORD" \
    -alias "$KEY_ALIAS" \
    -keyalg RSA -keysize 2048 -validity 10950 \
    -dname "CN=Roulette Android, OU=Release, O=yuushi2024, L=Tokyo, ST=Tokyo, C=JP"
  umask 077
  cat > "$PROPERTIES_PATH" <<PROPERTIES
# Generated by scripts/build-release.sh. Keep private; do not commit.
storePassword=$STORE_PASSWORD
keyAlias=$KEY_ALIAS
keyPassword=$KEY_PASSWORD
PROPERTIES
  echo "Wrote signing passwords to $PROPERTIES_PATH"
  export ROULETTE_STORE_PASSWORD="$STORE_PASSWORD"
  export ROULETTE_KEY_PASSWORD="$KEY_PASSWORD"
else
  # Fall back to the stored values per field, so an existing key can be signed
  # with only some of the variables set in the environment.
  export ROULETTE_STORE_PASSWORD="${ROULETTE_STORE_PASSWORD:-$(read_property storePassword || true)}"
  export ROULETTE_KEY_ALIAS="${ROULETTE_KEY_ALIAS:-$(read_property keyAlias || echo "$KEY_ALIAS")}"
  export ROULETTE_KEY_PASSWORD="${ROULETTE_KEY_PASSWORD:-$(read_property keyPassword || true)}"
fi

if [[ -z "${ROULETTE_STORE_PASSWORD:-}" || -z "${ROULETTE_KEY_PASSWORD:-}" ]]; then
  echo "Signing passwords are missing." >&2
  echo "Provide them with ROULETTE_STORE_PASSWORD / ROULETTE_KEY_PASSWORD," >&2
  echo "or remove $KEYSTORE_PATH to generate a fresh key." >&2
  exit 1
fi

export ROULETTE_KEYSTORE="$KEYSTORE_PATH"
export ROULETTE_KEY_ALIAS="${ROULETTE_KEY_ALIAS:-$KEY_ALIAS}"

./gradlew :app:clean :app:testDebugUnitTest :app:assembleRelease

VERSION_NAME="$(grep -oP 'versionName\s*=\s*"\K[^"]+' app/build.gradle.kts | head -1)"
APK_NAME="roulette-android-${VERSION_NAME}.apk"

mkdir -p release
cp app/build/outputs/apk/release/app-release.apk "release/$APK_NAME"
(cd release && sha256sum "$APK_NAME" > SHA256SUMS.txt)

echo "Signed APK written to release/$APK_NAME"
